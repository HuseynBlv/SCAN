package az.cci.scan.retailer;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneId;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Collectors;

import static az.cci.scan.retailer.RetailerOpportunityDtos.Evidence;
import static az.cci.scan.retailer.RetailerOpportunityDtos.Opportunity;
import static az.cci.scan.retailer.RetailerOpportunityDtos.OpportunityType;
import static az.cci.scan.retailer.RetailerOpportunityDtos.Priority;
import static az.cci.scan.retailer.RetailerOpportunityDtos.RecommendedAction;
import static az.cci.scan.retailer.RetailerOpportunityDtos.Status;

/** Pure, deterministic basket analytics. No score, claim, or recommendation is generated by an LLM. */
final class OpportunityDetectionEngine {
    static final int MIN_BASKETS = 30;
    static final int MIN_PAIR_BASKETS = 5;
    static final BigDecimal MIN_MAPPING_COVERAGE = BigDecimal.valueOf(85);

    record Line(String receiptId, String storeId, Instant timestamp, String product, String category, boolean mapped) {}
    private record Basket(String id, String storeId, Instant timestamp, Set<String> products, Map<String, String> categories, long lines, long mappedLines) {}
    private record Pair(String left, String right) {}

    List<Opportunity> detect(List<Line> lines, ZoneId zone, Instant analyzedAt) {
        if (lines.isEmpty()) return List.of();
        List<Basket> all = baskets(lines);
        if (all.size() < MIN_BASKETS) return List.of();
        Instant latest = all.stream().map(Basket::timestamp).max(Instant::compareTo).orElseThrow();
        Instant from = latest.minusSeconds(30L * 86_400L);
        List<Basket> recent = all.stream().filter(b -> !b.timestamp().isBefore(from)).toList();
        if (recent.size() < MIN_BASKETS) return List.of();

        List<Opportunity> result = new ArrayList<>();
        recent.stream().collect(Collectors.groupingBy(Basket::storeId, TreeMap::new, Collectors.toList()))
            .forEach((store, storeBaskets) -> {
                if (storeBaskets.size() < MIN_BASKETS) return;
                result.addAll(crossSell(store, storeBaskets, zone, analyzedAt));
                result.addAll(attachment(store, storeBaskets, zone, analyzedAt));
                result.addAll(timePattern(store, storeBaskets, zone, analyzedAt));
                result.addAll(trends(store, all.stream().filter(b -> b.storeId().equals(store)).toList(), zone, analyzedAt));
            });
        return result.stream()
            .sorted(Comparator.comparing((Opportunity o) -> priorityRank(o.priority()))
                .thenComparing(Opportunity::type).thenComparing(Opportunity::id))
            .limit(30).toList();
    }

    private List<Opportunity> crossSell(String store, List<Basket> baskets, ZoneId zone, Instant now) {
        Map<String, Long> productCounts = new HashMap<>();
        baskets.forEach(b -> b.products().forEach(p -> productCounts.merge(p, 1L, Long::sum)));
        Set<String> eligible = productCounts.entrySet().stream().filter(e -> e.getValue() >= MIN_PAIR_BASKETS)
            .sorted(Map.Entry.<String, Long>comparingByValue().reversed()).limit(40).map(Map.Entry::getKey).collect(Collectors.toSet());
        Map<Pair, Long> pairs = new HashMap<>();
        for (Basket basket : baskets) {
            List<String> products = basket.products().stream().filter(eligible::contains).sorted().toList();
            for (int i = 0; i < products.size(); i++) for (int j = i + 1; j < products.size(); j++) {
                pairs.merge(new Pair(products.get(i), products.get(j)), 1L, Long::sum);
            }
        }
        return pairs.entrySet().stream().filter(e -> e.getValue() >= MIN_PAIR_BASKETS).map(entry -> {
            Pair pair = entry.getKey(); long together = entry.getValue(); long total = baskets.size();
            long a = productCounts.get(pair.left()); long b = productCounts.get(pair.right());
            BigDecimal support = pct(together, total); BigDecimal confidence = pct(together, a);
            BigDecimal lift = decimal((together * (double) total) / (a * (double) b), 2);
            if (support.compareTo(BigDecimal.valueOf(2)) < 0 || lift.compareTo(BigDecimal.valueOf(1.30)) < 0) return null;
            Priority priority = lift.compareTo(BigDecimal.valueOf(2)) >= 0 && together >= 10 ? Priority.HIGH : Priority.MEDIUM;
            String observation = pair.left() + " and " + pair.right() + " appeared together in " + together + " of " + total + " analyzed baskets.";
            return opportunity(store, OpportunityType.CROSS_SELL, pair.left(), pair.right(), pair.left() + " + " + pair.right(),
                "A recurring product relationship is strong enough to test in-store.", priority,
                map("supportPercentage", support, "confidencePercentage", confidence, "lift", lift,
                    "productABaskets", BigDecimal.valueOf(a), "productBBaskets", BigDecimal.valueOf(b), "jointBaskets", BigDecimal.valueOf(together)),
                "Lift", lift + "×", evidence(baskets, zone, together, observation,
                    "A lift of " + lift + " means the pair occurred " + lift + " times as often as expected if the purchases were independent.", null),
                new RecommendedAction("Start placement trial", "Test placing the products closer together while SCAN compares the trial window with an equally long baseline.", 7), now);
        }).filter(java.util.Objects::nonNull).sorted(Comparator.comparing((Opportunity o) -> o.metrics().get("lift")).reversed()).limit(8).toList();
    }

    private List<Opportunity> attachment(String store, List<Basket> baskets, ZoneId zone, Instant now) {
        BigDecimal coverage = coverage(baskets);
        if (coverage.compareTo(MIN_MAPPING_COVERAGE) < 0) return List.of();
        long beverageBaskets = baskets.stream().filter(this::hasBeverage).count();
        if (beverageBaskets < MIN_PAIR_BASKETS) return List.of();
        BigDecimal overall = pct(beverageBaskets, baskets.size());
        Map<String, List<Basket>> categories = new HashMap<>();
        for (Basket basket : baskets) new HashSet<>(basket.categories().values()).stream()
            .filter(c -> !isBeverage(c) && !isUnmapped(c)).forEach(c -> categories.computeIfAbsent(c, ignored -> new ArrayList<>()).add(basket));
        BigDecimal threshold = overall.multiply(BigDecimal.valueOf(.65)).max(BigDecimal.TEN);
        return categories.entrySet().stream().filter(e -> e.getValue().size() >= 20).map(entry -> {
            long attached = entry.getValue().stream().filter(this::hasBeverage).count();
            BigDecimal rate = pct(attached, entry.getValue().size());
            if (rate.compareTo(threshold) > 0) return null;
            String category = entry.getKey(); long categoryBaskets = entry.getValue().size();
            return opportunity(store, OpportunityType.BEVERAGE_ATTACHMENT, category, null,
                category + " beverage attachment", "Beverages appear less often in these baskets than in the store overall.", Priority.MEDIUM,
                map("attachmentPercentage", rate, "storeBeveragePercentage", overall,
                    "categoryBaskets", BigDecimal.valueOf(categoryBaskets), "attachedBaskets", BigDecimal.valueOf(attached)),
                "Beverage attachment", rate + "%", evidence(baskets, zone, attached,
                    attached + " of " + categoryBaskets + " " + category.toLowerCase(Locale.ROOT) + " baskets included a beverage.",
                    "The observed attachment rate is " + rate + "% versus " + overall + "% across all store baskets.",
                    "This is a placement hypothesis, not evidence of lost sales."),
                new RecommendedAction("Start attachment trial", "Test a simple beverage prompt or adjacent placement for seven days.", 7), now);
        }).filter(java.util.Objects::nonNull).sorted(Comparator.comparing(o -> o.metrics().get("attachmentPercentage"))).limit(4).toList();
    }

    private List<Opportunity> trends(String store, List<Basket> all, ZoneId zone, Instant now) {
        Instant latest = all.stream().map(Basket::timestamp).max(Instant::compareTo).orElseThrow();
        Instant currentFrom = latest.minusSeconds(14L * 86_400L), priorFrom = currentFrom.minusSeconds(14L * 86_400L);
        List<Basket> current = all.stream().filter(b -> !b.timestamp().isBefore(currentFrom)).toList();
        List<Basket> prior = all.stream().filter(b -> !b.timestamp().isBefore(priorFrom) && b.timestamp().isBefore(currentFrom)).toList();
        if (current.size() < 20 || prior.size() < 20) return List.of();
        Map<String, Long> c = productCounts(current), p = productCounts(prior);
        Set<String> products = new HashSet<>(c.keySet()); products.addAll(p.keySet());
        return products.stream().map(product -> {
            long currentCount = c.getOrDefault(product, 0L), priorCount = p.getOrDefault(product, 0L);
            if (Math.max(currentCount, priorCount) < 8 || Math.min(currentCount, priorCount) < 3) return null;
            BigDecimal currentRate = pct(currentCount, current.size()), priorRate = pct(priorCount, prior.size());
            if (priorRate.signum() == 0) return null;
            BigDecimal change = currentRate.subtract(priorRate).multiply(BigDecimal.valueOf(100)).divide(priorRate, 1, RoundingMode.HALF_UP);
            if (change.abs().compareTo(BigDecimal.valueOf(30)) < 0) return null;
            boolean growth = change.signum() > 0;
            return opportunity(store, OpportunityType.PRODUCT_TREND, product, null,
                product + (growth ? " demand growth" : " sales decline"),
                "Basket penetration changed materially across two equivalent 14-day windows.", growth ? Priority.MEDIUM : Priority.HIGH,
                map("currentBasketPercentage", currentRate, "priorBasketPercentage", priorRate, "relativeChangePercentage", change.abs(),
                    "currentBaskets", BigDecimal.valueOf(currentCount), "priorBaskets", BigDecimal.valueOf(priorCount)),
                growth ? "Growth" : "Decline", (growth ? "+" : "−") + change.abs() + "%", evidence(current, zone, currentCount,
                    product + " appeared in " + currentCount + " of " + current.size() + " recent baskets, versus " + priorCount + " of " + prior.size() + " in the prior window.",
                    "Rates are compared instead of raw sales so differing basket coverage is accounted for.",
                    "The change is observational and may reflect availability, seasonality, price, or local events."),
                new RecommendedAction(growth ? "Check availability" : "Review visibility", growth ? "Confirm stock and shelf capacity can support the observed demand." : "Check stock, price, and shelf visibility before changing the range.", 7), now);
        }).filter(java.util.Objects::nonNull).sorted(Comparator.comparing(o -> o.metrics().get("relativeChangePercentage"), Comparator.reverseOrder())).limit(5).toList();
    }

    private List<Opportunity> timePattern(String store, List<Basket> baskets, ZoneId zone, Instant now) {
        List<Basket> beverageSnack = baskets.stream().filter(b -> hasBeverage(b) && b.categories().values().stream().anyMatch(this::isSnack)).toList();
        if (beverageSnack.size() < 20) return List.of();
        Map<String, Long> parts = beverageSnack.stream().collect(Collectors.groupingBy(b -> daypart(b.timestamp().atZone(zone).getHour()), Collectors.counting()));
        Map.Entry<String, Long> peak = parts.entrySet().stream().max(Map.Entry.<String, Long>comparingByValue().thenComparing(Map.Entry::getKey)).orElseThrow();
        BigDecimal share = pct(peak.getValue(), beverageSnack.size());
        if (share.compareTo(BigDecimal.valueOf(45)) < 0) return List.of();
        return List.of(opportunity(store, OpportunityType.TIME_PATTERN, "Beverages", "Snacks",
            peak.getKey() + " beverage-and-snack window", "Beverage-and-snack baskets are concentrated in one observed daypart.", Priority.LOW,
            map("peakSharePercentage", share, "supportingBaskets", BigDecimal.valueOf(peak.getValue()), "pairedBaskets", BigDecimal.valueOf(beverageSnack.size())),
            "Peak-window share", share + "%", evidence(baskets, zone, peak.getValue(),
                peak.getValue() + " of " + beverageSnack.size() + " beverage-and-snack baskets occurred during " + peak.getKey().toLowerCase(Locale.ROOT) + ".",
                "This concentration identifies when execution matters most; it does not predict incremental sales.", null),
            new RecommendedAction("Plan peak-window check", "Check availability and display execution before the observed peak window.", 7), now));
    }

    private Opportunity opportunity(String store, OpportunityType type, String a, String b, String title, String description,
                                    Priority priority, Map<String, BigDecimal> metrics, String metricLabel, String metricValue,
                                    Evidence evidence, RecommendedAction action, Instant now) {
        String id = stableId(type + "|" + store + "|" + a + "|" + (b == null ? "" : b));
        return new Opportunity(id, store, type, title, description, b == null ? List.of(a) : List.of(a, b), priority,
            Status.DETECTED, metrics, metricLabel, metricValue, evidence, action, null, now, now);
    }

    private Evidence evidence(List<Basket> baskets, ZoneId zone, long supporting, String observed, String matters, String limitation) {
        LocalDate from = baskets.stream().map(b -> b.timestamp().atZone(zone).toLocalDate()).min(LocalDate::compareTo).orElseThrow();
        LocalDate to = baskets.stream().map(b -> b.timestamp().atZone(zone).toLocalDate()).max(LocalDate::compareTo).orElseThrow();
        return new Evidence(baskets.size(), supporting, from, to, coverage(baskets), observed, matters, limitation);
    }

    private List<Basket> baskets(List<Line> lines) {
        Map<String, List<Line>> grouped = lines.stream().collect(Collectors.groupingBy(Line::receiptId, LinkedHashMap::new, Collectors.toList()));
        return grouped.values().stream().map(group -> {
            Line first = group.getFirst(); Map<String, String> products = new LinkedHashMap<>();
            group.forEach(line -> products.putIfAbsent(line.product(), line.category()));
            return new Basket(first.receiptId(), first.storeId(), first.timestamp(), Set.copyOf(products.keySet()), Map.copyOf(products),
                group.size(), group.stream().filter(Line::mapped).count());
        }).toList();
    }

    private Map<String, Long> productCounts(List<Basket> baskets) {
        Map<String, Long> result = new HashMap<>(); baskets.forEach(b -> b.products().forEach(p -> result.merge(p, 1L, Long::sum))); return result;
    }
    private boolean hasBeverage(Basket basket) { return basket.categories().values().stream().anyMatch(this::isBeverage); }
    private boolean isBeverage(String category) { String c = category.toLowerCase(Locale.ROOT); return c.contains("beverage") || c.contains("drink") || c.contains("water") || c.contains("juice") || c.contains("tea") || c.contains("soda"); }
    private boolean isSnack(String category) { String c = category.toLowerCase(Locale.ROOT); return c.contains("snack") || c.contains("chip") || c.contains("confection") || c.contains("biscuit"); }
    private boolean isUnmapped(String category) { return category == null || category.isBlank() || category.equalsIgnoreCase("Unmapped"); }
    private BigDecimal coverage(List<Basket> baskets) { long total = baskets.stream().mapToLong(Basket::lines).sum(); long mapped = baskets.stream().mapToLong(Basket::mappedLines).sum(); return pct(mapped, total); }
    private static BigDecimal pct(long n, long d) { return d == 0 ? BigDecimal.ZERO.setScale(1) : BigDecimal.valueOf(n * 100d / d).setScale(1, RoundingMode.HALF_UP); }
    private static BigDecimal decimal(double n, int scale) { return BigDecimal.valueOf(n).setScale(scale, RoundingMode.HALF_UP); }
    private static String daypart(int hour) { if (hour < 6) return "NIGHT"; if (hour < 11) return "MORNING"; if (hour < 15) return "MIDDAY"; if (hour < 18) return "AFTERNOON"; if (hour < 22) return "EVENING"; return "NIGHT"; }
    private static int priorityRank(Priority priority) { return switch (priority) { case HIGH -> 0; case MEDIUM -> 1; case LOW -> 2; }; }
    private static Map<String, BigDecimal> map(Object... values) { Map<String, BigDecimal> result = new LinkedHashMap<>(); for (int i = 0; i < values.length; i += 2) result.put((String) values[i], (BigDecimal) values[i + 1]); return Map.copyOf(result); }
    static String stableId(String value) { try { byte[] hash = MessageDigest.getInstance("SHA-256").digest(value.toLowerCase(Locale.ROOT).getBytes(StandardCharsets.UTF_8)); return "opp-" + java.util.HexFormat.of().formatHex(hash, 0, 12); } catch (NoSuchAlgorithmException e) { throw new IllegalStateException(e); } }
}
